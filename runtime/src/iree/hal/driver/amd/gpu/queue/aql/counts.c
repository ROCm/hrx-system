void iree_hal_amd_gpu_aql_count_prepare(
    const iree_hal_amd_gpu_kernarg_layout_t* layout,
    const iree_hal_amd_gpu_dispatch_geometry_t* geometry,
    iree_hal_dispatch_flags_t flags, uint32_t packet_offset,
    uint32_t value_index, uint64_t count_offset, uint32_t argument_offset,
    iree_hal_amd_gpu_aql_count_t* out_count) {
  iree_hal_amd_gpu_aql_indirect_arguments_t indirect;
  iree_hal_amd_gpu_aql_indirect_prepare(layout, geometry, flags, 0, 0, 0, 0,
                                        &indirect);
  *out_count = (iree_hal_amd_gpu_aql_count_t){
      .packet_offset = packet_offset,
      .value_index = value_index,
      .count_offset = count_offset,
      .argument_offset = argument_offset,
  };
  for (uint32_t i = 0; i < 3; ++i) {
    // Admitted workgroup dimensions and complete kernarg extents fit uint16_t.
    // An absent UINT32_MAX offset therefore maps uniquely to UINT16_MAX.
    out_count->workgroup_size[i] = (uint16_t)indirect.workgroup_size[i];
    out_count->hidden_offsets[i] = (uint16_t)indirect.count_offsets[i];
  }
}
