"""Discovery of published Loom profiles on a model hub.

Only the hub's public HTTP API is used, through the standard library, so the
launcher works without the acquisition ``hf`` extra. Authentication is read from
the environment and sent only when present: the hub answers unauthenticated
reads for public repositories, and private or gated repositories report their
own error instead of being silently skipped.
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass, field, replace
from typing import Callable, Iterable

DEFAULT_ENDPOINT = "https://huggingface.co"
# Packages generated by the Loom porting workflow carry this tag.
PROFILE_TAG = "loom-serve"
_USER_AGENT = "loom-launch/1"

# A transport answers one request with a status and the complete body.
Transport = Callable[[str, dict[str, str]], tuple[int, bytes]]


class HubError(RuntimeError):
    """A hub request failed for a reason the caller cannot retry locally."""


class HubUnreachable(HubError):
    """The hub could not be contacted at all."""


class HubAuthRequired(HubError):
    """The hub requires credentials for this repository."""


class HubNotFound(HubError):
    """The hub has no such repository, revision or file (HTTP 404)."""


def _urllib_transport(url: str, headers: dict[str, str]) -> tuple[int, bytes]:
    request = urllib.request.Request(url, headers=headers, method="GET")
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read() or b""
    except urllib.error.URLError as exc:
        raise HubUnreachable(f"cannot reach {url}: {exc.reason}") from exc
    except TimeoutError as exc:
        raise HubUnreachable(f"timed out reading {url}") from exc


@dataclass(frozen=True)
class HubModel:
    """One repository as the hub describes it."""

    repo: str
    #: Hub revision (`sha`) the search observed, when reported.
    revision: str | None = None
    tags: tuple[str, ...] = ()
    pipeline_tag: str | None = None
    last_modified: str | None = None
    downloads: int = 0
    likes: int = 0
    gated: bool = False
    #: Root names of the repository's files, when the listing asked for them.
    siblings: tuple[str, ...] = ()
    #: The hub's own card metadata: tags, base model and free-form fields.
    card_data: dict = field(default_factory=dict)

    @property
    def author(self) -> str:
        return self.repo.split("/", 1)[0]

    @property
    def short_name(self) -> str:
        return self.repo.split("/", 1)[-1]

    def has_file(self, *names: str) -> bool:
        """True when every named file is a root file of the repository."""
        if not self.siblings:
            return False
        available = set(self.siblings)
        return all(name in available for name in names)

    @property
    def base_model(self) -> str | None:
        value = self.card_data.get("base_model")
        if isinstance(value, str):
            return value
        # Finetunes report a list of base-model tags instead of one field.
        for tag in self.tags:
            if tag.startswith("base_model:"):
                return tag[len("base_model:") :].split(":")[-1]
        return None

    def describe(self) -> dict:
        """Machine-readable form used by `--json` output."""
        return {
            "repo": self.repo,
            "author": self.author,
            "name": self.short_name,
            "revision": self.revision,
            "pipeline_tag": self.pipeline_tag,
            "tags": list(self.tags),
            "base_model": self.base_model,
            "last_modified": self.last_modified,
            "downloads": self.downloads,
            "likes": self.likes,
            "gated": self.gated,
            "files": list(self.siblings),
        }


class Hub:
    """A model-hub client with an injectable transport for tests."""

    def __init__(
        self,
        endpoint: str | None = None,
        token: str | None = None,
        *,
        transport: Transport | None = None,
    ):
        self.endpoint = (
            endpoint or os.environ.get("LOOM_HUB_ENDPOINT") or DEFAULT_ENDPOINT
        ).rstrip("/")
        if token is None:
            token = os.environ.get("HF_TOKEN") or os.environ.get(
                "HUGGING_FACE_HUB_TOKEN"
            )
        self._token = token
        self._transport = transport or _urllib_transport
        self._json_cache: dict[str, object] = {}
        self._raw_cache: dict[tuple[str, str, str], bytes] = {}

    # -- requests -----------------------------------------------------------
    def _headers(self) -> dict[str, str]:
        headers = {"User-Agent": _USER_AGENT, "Accept": "application/json"}
        if self._token:
            headers["Authorization"] = f"Bearer {self._token}"
        return headers

    def _get(self, url: str) -> bytes:
        status, body = self._transport(url, self._headers())
        if status in (401, 403):
            raise HubAuthRequired(
                f"{url} requires credentials: run `hf auth login`, or set HF_TOKEN "
                "for the account that was granted access"
            )
        if status == 404:
            raise HubNotFound(f"{url} was not found")
        if status >= 400:
            detail = body[:200].decode("utf-8", "replace").strip()
            raise HubError(f"{url} answered HTTP {status}: {detail}")
        return body

    def _get_json(self, url: str) -> object:
        if url in self._json_cache:
            return self._json_cache[url]
        body = self._get(url)
        try:
            document = json.loads(body)
        except json.JSONDecodeError as exc:
            raise HubError(f"{url} did not return JSON: {exc}") from exc
        self._json_cache[url] = document
        return document

    # -- discovery ----------------------------------------------------------
    def search(
        self,
        query: str | None = None,
        *,
        author: str | None = None,
        tags: Iterable[str] = (),
        limit: int = 50,
        with_files: bool = True,
    ) -> list[HubModel]:
        """Lists matching repositories, newest activity first.

        `query` matches repository names; `tags` filters on hub tags. Searching
        for an owner prefix ("loom-fun/") is accepted as a convenience and
        becomes an author filter.
        """
        if query and query.endswith("/") and not author:
            candidate = query.rstrip("/")
            if self._looks_like_author(candidate):
                author = candidate
                query = None
        parameters: list[tuple[str, str]] = [
            ("limit", str(max(1, min(limit, 1000)))),
            ("sort", "lastModified"),
            ("direction", "-1"),
        ]
        if with_files:
            parameters.append(("full", "true"))
        if query:
            parameters.append(("search", query))
        if author:
            parameters.append(("author", author))
        for tag in tags:
            parameters.append(("filter", tag))
        url = f"{self.endpoint}/api/models?" + urllib.parse.urlencode(parameters)
        document = self._get_json(url)
        if not isinstance(document, list):
            raise HubError(f"{url} did not return a repository list")
        models = (_hub_model(entry) for entry in document if entry)
        return [model for model in models if model is not None]

    @staticmethod
    def _looks_like_author(name: str) -> bool:
        return bool(name) and all(
            character.isalnum() or character in "-_." for character in name
        )

    def model(self, repo: str) -> HubModel:
        """Reads one repository's metadata and root file names."""
        url = f"{self.endpoint}/api/models/{urllib.parse.quote(repo)}?full=true"
        document = self._get_json(url)
        model = _hub_model(document) if isinstance(document, dict) else None
        if model is None:
            raise HubError(f"{repo} does not describe a repository")
        return model

    def profiles(
        self,
        query: str | None = None,
        *,
        author: str | None = None,
        limit: int = 50,
        tags: Iterable[str] = (PROFILE_TAG,),
    ) -> list[HubModel]:
        """Lists repositories that publish an installable Loom profile."""
        found = self.search(query, author=author, tags=tags, limit=limit)
        # A profile publishes a root model card; a catalog-only repository needs
        # an explicit catalog selector, so it is not offered as a bare profile.
        return [model for model in found if model.has_file("model.json")]

    # -- file reads ---------------------------------------------------------
    def raw(self, repo: str, path: str, revision: str | None = None) -> bytes:
        revision = revision or "main"
        key = (repo, revision, path)
        cached = self._raw_cache.get(key)
        if cached is not None:
            return cached
        url = (
            f"{self.endpoint}/{urllib.parse.quote(repo)}/raw/"
            f"{urllib.parse.quote(revision)}/{urllib.parse.quote(path)}"
        )
        body = self._get(url)
        self._raw_cache[key] = body
        return body

    def raw_optional(self, repo: str, path: str, revision: str | None = None) -> bytes:
        """Reads one file, treating an absent file as empty."""
        try:
            return self.raw(repo, path, revision)
        except HubError as exc:
            message = str(exc)
            if "404" in message or "was not found" in message:
                return b""
            raise

    def json_optional(self, repo: str, path: str, revision: str | None = None) -> dict:
        """Reads one JSON document, treating an absent or invalid file as empty."""
        body = self.raw_optional(repo, path, revision)
        if not body:
            return {}
        try:
            document = json.loads(body)
        except json.JSONDecodeError:
            return {}
        return document if isinstance(document, dict) else {}


def _hub_model(entry: object) -> HubModel | None:
    if not isinstance(entry, dict):
        return None
    repo = entry.get("id") or entry.get("modelId")
    if not isinstance(repo, str) or not repo:
        return None
    tags = entry.get("tags")
    siblings = entry.get("siblings")
    card_data = entry.get("cardData")
    return HubModel(
        repo=repo,
        revision=_string(entry.get("sha")),
        tags=tuple(tag for tag in tags if isinstance(tag, str))
        if isinstance(tags, list)
        else (),
        pipeline_tag=_string(entry.get("pipeline_tag")),
        last_modified=_string(entry.get("lastModified")),
        downloads=_integer(entry.get("downloads")),
        likes=_integer(entry.get("likes")),
        gated=bool(entry.get("gated")),
        siblings=tuple(
            sibling["rfilename"]
            for sibling in siblings
            if isinstance(sibling, dict) and isinstance(sibling.get("rfilename"), str)
        )
        if isinstance(siblings, list)
        else (),
        card_data=card_data if isinstance(card_data, dict) else {},
    )


def _string(value: object) -> str | None:
    return value if isinstance(value, str) and value else None


def _integer(value: object) -> int:
    return value if isinstance(value, int) else 0


def with_revision(model: HubModel, revision: str | None) -> HubModel:
    """Returns `model` pinned to `revision`."""
    return replace(model, revision=revision)
