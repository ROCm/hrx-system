static bool loom_vector_to_scalar_descriptor_is_empty(
    const loom_vector_to_scalar_descriptor_t* descriptor) {
  return descriptor->lane_kind == LOOM_VECTOR_TO_SCALAR_LANE_GENERIC &&
         descriptor->lane_op_kind == LOOM_OP_KIND_UNKNOWN;
}

const loom_vector_to_scalar_descriptor_t* loom_vector_to_scalar_find_descriptor(
    loom_op_kind_t kind) {
  if (loom_op_dialect_id(kind) != LOOM_DIALECT_VECTOR) return NULL;
  const uint8_t op_index = loom_op_dialect_index(kind);
  if (op_index >= IREE_ARRAYSIZE(kVectorToScalarDescriptors)) return NULL;
  const loom_vector_to_scalar_descriptor_t* descriptor =
      &kVectorToScalarDescriptors[op_index];
  return loom_vector_to_scalar_descriptor_is_empty(descriptor) ? NULL
                                                               : descriptor;
}
