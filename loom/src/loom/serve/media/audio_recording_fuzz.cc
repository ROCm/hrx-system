namespace {

constexpr size_t kMaximumInputLength = 64 * 1024;
constexpr iree_host_size_t kMaximumDecodedBytes = 256 * 1024;

struct AudioInput {
  // MIME type supplied at the upload boundary.
  std::string content_type;
  // Generated bytes owning validity-preserving PCM or WAV input.
  std::vector<uint8_t> storage;
  // Arbitrary bytes borrowed directly from the current mutation.
  iree_const_byte_span_t borrowed_data;
  // Whether this structured form must survive complete recording admission.
  bool require_success = false;

  iree_const_byte_span_t data() const {
    return storage.empty()
               ? borrowed_data
               : iree_make_const_byte_span(storage.data(), storage.size());
  }
};

std::vector<uint8_t> MakeS16(iree_const_byte_span_t payload) {
  const size_t count = payload.data_length ? payload.data_length : 1;
  std::vector<uint8_t> samples(count * sizeof(int16_t));
  for (size_t i = 0; i < count; ++i) {
    const uint8_t value = payload.data_length ? payload.data[i] : 0;
    const int16_t sample =
        static_cast<int16_t>((static_cast<int32_t>(value) - 128) * 256);
    iree_unaligned_store_le_u16(samples.data() + i * sizeof(sample), sample);
  }
  return samples;
}

std::vector<uint8_t> MakeF32(iree_const_byte_span_t payload) {
  const size_t count = payload.data_length ? payload.data_length : 1;
  std::vector<uint8_t> samples(count * sizeof(float));
  for (size_t i = 0; i < count; ++i) {
    const uint8_t value = payload.data_length ? payload.data[i] : 128;
    const float sample =
        static_cast<float>(static_cast<int32_t>(value) - 128) / 128.0f;
    iree_unaligned_store_le_f32(samples.data() + i * sizeof(sample), sample);
  }
  return samples;
}

std::vector<uint8_t> MakeWave(iree_const_byte_span_t payload) {
  std::vector<uint8_t> samples = MakeS16(payload);
  std::vector<uint8_t> wave(44 + samples.size());
  memcpy(wave.data(), "RIFF", 4);
  iree_unaligned_store_le_u32(wave.data() + 4, wave.size() - 8);
  memcpy(wave.data() + 8, "WAVEfmt ", 8);
  iree_unaligned_store_le_u32(wave.data() + 16, 16);
  iree_unaligned_store_le_u16(wave.data() + 20, 1);
  iree_unaligned_store_le_u16(wave.data() + 22, 1);
  iree_unaligned_store_le_u32(wave.data() + 24, 16000);
  iree_unaligned_store_le_u32(wave.data() + 28, 16000 * sizeof(int16_t));
  iree_unaligned_store_le_u16(wave.data() + 32, sizeof(int16_t));
  iree_unaligned_store_le_u16(wave.data() + 34, 16);
  memcpy(wave.data() + 36, "data", 4);
  iree_unaligned_store_le_u32(wave.data() + 40, samples.size());
  memcpy(wave.data() + 44, samples.data(), samples.size());
  return wave;
}

AudioInput GenerateInput(const uint8_t* data, size_t size) {
  const iree_const_byte_span_t payload =
      iree_make_const_byte_span(data + 1, size - 1);
  AudioInput input;
  switch (data[0]) {
    case 'S':
      input.content_type = "audio/pcm;format=s16le;rate=16000;channels=1";
      input.storage = MakeS16(payload);
      input.require_success = true;
      break;
    case 'F':
      input.content_type = "audio/pcm;format=f32le;rate=48000;channels=1";
      input.storage = MakeF32(payload);
      input.require_success = true;
      break;
    case 'W':
      input.content_type = "audio/wav";
      input.storage = MakeWave(payload);
      input.require_success = LOOM_FUZZ_AUDIO_WAV;
      break;
    case 'T': {
      const iree_string_view_t combined = iree_make_string_view(
          reinterpret_cast<const char*>(payload.data), payload.data_length);
      iree_string_view_t media_type;
      iree_string_view_t audio;
      iree_string_view_split(combined, '\n', &media_type, &audio);
      input.content_type.assign(media_type.data, media_type.size);
      input.borrowed_data = iree_make_const_byte_span(audio.data, audio.size);
      return input;
    }
    default:
      input.content_type = "application/octet-stream";
      input.borrowed_data = iree_make_const_byte_span(data, size);
      return input;
  }
  return input;
}

void Exercise(const AudioInput& input) {
  loom_serve_audio_source_t source;
  iree_status_t status = loom_serve_audio_source_parse(
      iree_make_string_view(input.content_type.data(),
                            input.content_type.size()),
      input.data(), &source);
  loom_serve_audio_recording_t* recording = nullptr;
  if (iree_status_is_ok(status)) {
    status = loom_serve_audio_recording_allocate(
        &source, kMaximumDecodedBytes, iree_allocator_system(), &recording);
  }
  if (input.require_success && !iree_status_is_ok(status)) {
    IREE_CHECK_OK(status);
  }
  loom_serve_audio_recording_free(recording);
  iree_status_free(status);
}

}  // namespace

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  if (!size || size > kMaximumInputLength) {
    return 0;
  }
  Exercise(GenerateInput(data, size));
  return 0;
}
